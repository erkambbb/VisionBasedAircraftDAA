"""Writes city_airports.py: every land airport in X-Plane's apt.dat within RADIUS_KM of a city in
fleet_core.CITIES, so the ownship can keep away from them (no aircraft on the ground in a frame).

Run from src/data_generation after changing CITIES:
    python3 -m make_city_airports
"""
import sys
sys.path.append('..')

import math
import os
import pprint

XP_DIR = os.path.expanduser("~/.local/share/Steam/steamapps/common/X-Plane 11")
APT_DATS = ("Custom Scenery/Global Airports/Earth nav data/apt.dat",
            "Resources/default scenery/default apt dat/Earth nav data/apt.dat")
RADIUS_KM = 45.0


def cities():
    """{name: (lat, lon)} read from fleet_core.py without importing it (it imports our output)."""
    src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "fleet_core.py")).read()
    block = src[src.index("CITIES = {"):]
    block = block[:block.index("\n}\n") + 3]
    ns = {}
    exec(block, ns)
    return {k: v[:2] for k, v in ns["CITIES"].items()}


def km(lat1, lon1, lat2, lon2):
    x = (lon2 - lon1) * math.cos(math.radians((lat1 + lat2) / 2)) * 111.32
    return math.hypot(x, (lat2 - lat1) * 111.32)


def parse(path, centers):
    """[(city, ident, lat, lon, longest runway m)] for land airports (row code 1) with runways."""
    out, cur = [], None

    def flush():
        if cur and cur["rw"]:
            lat = sum(p[0] for p in cur["pts"]) / len(cur["pts"])
            lon = sum(p[1] for p in cur["pts"]) / len(cur["pts"])
            for city, (clat, clon) in centers.items():
                if km(lat, lon, clat, clon) <= RADIUS_KM:
                    out.append((city, cur["id"], round(lat, 5), round(lon, 5), round(max(cur["rw"]))))

    with open(path, errors="replace") as f:
        for line in f:
            code = line[:4].split(" ", 1)[0]
            if code in ("1", "16", "17"):
                flush()
                p = line.split()
                cur = {"id": p[4], "rw": [], "pts": []} if code == "1" and len(p) > 4 else None
            elif code == "100" and cur is not None:
                p = line.split()
                try:
                    a = (float(p[9]), float(p[10]))
                    b = (float(p[18]), float(p[19]))
                except (IndexError, ValueError):
                    continue
                cur["pts"] += [a, b]
                cur["rw"].append(km(*a, *b) * 1000.0)
    flush()
    return out


def main():
    centers = cities()
    found = {}
    for rel in APT_DATS:
        path = os.path.join(XP_DIR, rel)
        if os.path.exists(path):
            for city, ident, lat, lon, rw in parse(path, centers):
                found.setdefault(city, {}).setdefault(ident, (ident, lat, lon, rw))
    table = {c: tuple(sorted(found.get(c, {}).values())) for c in centers}
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "city_airports.py")
    with open(out, "w") as f:
        f.write('"""Generated by make_city_airports.py from X-Plane apt.dat: land airports within '
                f'{RADIUS_KM:.0f} km of each city.\n(ident, lat, lon, longest runway m)."""\n')
        f.write("AIRPORTS = " + pprint.pformat(table, width=110, sort_dicts=False) + "\n")
    for c, a in table.items():
        print(f"{c}: {len(a)} havalimanı")


if __name__ == "__main__":
    main()
